#!/usr/bin/env node
/**
 * Concatenate the client sources into the module-loader factory the Desktop app
 * loads from `lib/client.js`.
 *
 * The browser bundle format is fixed by the client module system: one script
 * registers a CommonJS factory under the package name, and the factory's
 * `require` resolves baseline modules from the page's module table. This build
 * inlines the package's own modules in a fixed order so the artifact carries no
 * relative `require`, and adds the registration wrapper the table expects.
 *
 * Usage: `node src/client/build.cjs [--check]`; `--check` writes nothing and
 * fails when `lib/client.js` differs from the sources.
 */

'use strict'

const { readFileSync, writeFileSync, mkdirSync } = require('node:fs')
const { join } = require('node:path')
const esbuild = require('esbuild')

const root = join(__dirname, '..', '..')
const PACKAGE_NAME = 'dsh-team-model-policy'

/** Own modules inlined into the factory, in dependency order. */
const MODULES = ['locale.cjs', 'team-locale.cjs', 'subagent-locale.cjs', 'subagent-filter.cjs', 'styles.cjs', 'card.cjs', 'view.cjs', 'team-view.cjs', 'subagent-view.cjs', 'index.cjs']

/** Strip the leading JSDoc/line banner a source may start with before wrapping. */
function body(source) {
  return source.replace(/\r\n/g, '\n').trimEnd() + '\n'
}

/** Build the factory source the module loader registers. */
function build() {
  const views = {}
  for (const name of ['team-view', 'subagent-view']) {
    const compiled = esbuild.buildSync({ entryPoints: [join(__dirname, name + '.tsx')], bundle: true, write: false,
      outfile: join(root, 'lib', name + '.cjs'), format: 'cjs', platform: 'browser', target: 'es2022',
      loader: { '.css': 'local-css' }, external: ['react', 'react-dom', '@deepseek-ai/*'], jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment' })
    const js = compiled.outputFiles.find(file => file.path.endsWith('.cjs')).text
    const css = compiled.outputFiles.find(file => file.path.endsWith('.css')).text
    views[name + '.cjs'] = js + '\nmodule.exports.styles = ' + JSON.stringify(css) + ';\n'
  }
  const parts = []
  parts.push('/**')
  parts.push(' * Generated by src/client/build.cjs from src/client/*.cjs. Do not edit by hand.')
  parts.push(' *')
  parts.push(' * Registers this package\'s client half as a module-loader factory: the factory')
  parts.push(' * receives the page module table\'s \`require\`, so only baseline modules are')
  parts.push(' * requested, and the package\'s own modules are inlined in dependency order.')
  parts.push(' */')
  parts.push('window.__ModuleLoader__.load({')
  parts.push('  id: ' + JSON.stringify(PACKAGE_NAME) + ',')
  parts.push('  factory: (require) => {')
  parts.push('    const __modules = {}')
  parts.push('    const __cache = {}')
  parts.push('    function __define(name, fn) { __modules[name] = fn }')
  parts.push('    function __require(name) {')
  parts.push('      if (name.charAt(0) !== \'.\') return require(name)')
  parts.push('      const id = name.replace(/^\\.\\//, \'\')')
  parts.push('      if (__cache[id] !== undefined) return __cache[id].exports')
  parts.push('      const module = { exports: {} }')
  parts.push('      __cache[id] = module')
  parts.push('      __modules[id](module, module.exports, __require)')
  parts.push('      return module.exports')
  parts.push('    }')
  for (const name of MODULES) {
    const source = body(views[name] ?? readFileSync(join(__dirname, name), 'utf8'))
    parts.push('    __define(' + JSON.stringify(name) + ', (module, exports, require) => {')
    parts.push(source.split('\n').map(line => (line === '' ? line : '      ' + line)).join('\n').trimEnd())
    parts.push('    })')
  }
  parts.push('    return __require(\'./index.cjs\')')
  parts.push('  },')
  parts.push('})')
  return parts.join('\n') + '\n'
}

const generated = build()
const target = join(root, 'lib', 'client.js')
if (process.argv.includes('--check')) {
  let existing = ''
  try {
    existing = readFileSync(target, 'utf8')
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
  if (existing !== generated) {
    console.error('lib/client.js is out of date; run: node src/client/build.cjs')
    process.exitCode = 1
  } else {
    console.log('lib/client.js matches src/client/*.cjs')
  }
} else {
  mkdirSync(join(root, 'lib'), { recursive: true })
  writeFileSync(target, generated)
  console.log('wrote ' + target + ' (' + Buffer.byteLength(generated) + ' bytes)')
}
